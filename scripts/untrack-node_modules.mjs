import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
let tracked = '';
try {
  tracked = execSync('git ls-files node_modules', { cwd: root, encoding: 'utf8' }).trim();
} catch {
  console.error('请在仓库根目录执行，并确保已安装 git。');
  process.exit(1);
}
if (!tracked) {
  console.log('node_modules 不在 Git 索引中，无需处理。');
  process.exit(0);
}
console.log('正在从 Git 索引中移除 node_modules（不删磁盘上的目录）...');
try {
  execSync('git rm -r --cached -- node_modules', { cwd: root, stdio: 'inherit' });
  console.log('完成。请执行 git status 后提交。');
} catch {
  process.exit(1);
}
