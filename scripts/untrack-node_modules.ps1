# 若某次误执行了 `git add node_modules`，仅改 .gitignore 不会从 Git 中移除，Changes 会长期显示 1 万+ 文件。
# 在仓库根目录执行: powershell -ExecutionPolicy Bypass -File scripts/untrack-node_modules.ps1
$ErrorActionPreference = 'Stop'
Set-Location (Split-Path -Parent $PSScriptRoot)
$tracked = & git ls-files 'node_modules' 2>&1
if ($LASTEXITCODE -ne 0) {
  Write-Host 'Not a git repository or git failed.'
  exit 1
}
if (-not $tracked) {
  Write-Host 'node_modules 不在版本库中，无需处理。'
  exit 0
}
Write-Host '正在从 Git 索引中移除 node_modules（不删磁盘文件）...'
& git rm -r --cached -- 'node_modules'
Write-Host '完成。请检查 git status 后提交。'
